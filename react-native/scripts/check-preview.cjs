const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const app=fs.readFileSync(path.join(root,'src/App.tsx'),'utf8');
const math=fs.readFileSync(path.join(root,'src/domain.ts'),'utf8');
const cfg=JSON.parse(fs.readFileSync(path.join(root,'app.json'),'utf8'));
assert.equal(pkg.dependencies['react-native'],'0.81.5');
assert.equal(cfg.expo.android.package,'com.satraders.billing.preview');
assert(!app.includes('WebView'), 'Do not render or embed the old application');
assert(!app.includes('satradersbilling://'), 'Old Java route shortcuts are forbidden');
assert(!app.includes('Linking.openURL'), 'No URL wrapper navigation');
assert(app.includes('saveBill=async'), 'Native bill workflow missing');
assert(app.includes('recordChange=async'), 'Native payment/return workflow missing');
assert(app.includes('saveCustomer=async'), 'Native customer workflow missing');
assert(app.includes('saveStock=async'), 'Native inventory workflow missing');
assert(app.includes('saveNote=async'), 'Native slip/challan workflow missing');
assert(math.includes('calculateBill'), 'Native rental calculation missing');
assert(pkg.dependencies['@react-native-async-storage/async-storage']==='2.2.0');
console.log('Native-only UI and local workflow checks passed.');
