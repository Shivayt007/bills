const fs=require('fs');const path=require('path');const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const cfg=JSON.parse(fs.readFileSync(path.join(root,'app.json'),'utf8'));
const app=fs.readFileSync(path.join(root,'src/App.tsx'),'utf8');
assert.equal(pkg.dependencies['react-native'],'0.81.5');
assert.equal(cfg.expo.android.package,'com.satraders.billing.preview');
assert.notEqual(cfg.expo.android.package,'com.satraders.billing');
assert(app.includes('SAMPLE DATA ONLY'),'Preview data warning required');
assert(!app.includes('FirebaseFirestore'),'Native production logic must not be silently replaced');
assert(app.includes("type Tab = 'home'"),'Native tab navigation missing');
assert(app.includes('No matching sample bills'),'Bill search missing');
console.log('React Native preview safety checks passed');
